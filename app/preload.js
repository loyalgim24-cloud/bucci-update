const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('api', {
  search:        (kw)       => ipcRenderer.invoke('search', kw),
  searchBySlug:  (slug)     => ipcRenderer.invoke('search-by-slug', slug),
  searchUcApp:    (name)     => ipcRenderer.invoke('search-uc-app', name),
  searchAppMixed: (slug, name) => ipcRenderer.invoke('search-app-mixed', slug, name),
  buildCache:    ()         => ipcRenderer.invoke('build-cache'),
  rebuildUc:     ()         => ipcRenderer.invoke('rebuild-uc'),
  cacheStatus:   ()         => ipcRenderer.invoke('cache-status'),
  getAppList:    ()         => ipcRenderer.invoke('get-app-list'),
  getUpaCats:    ()         => ipcRenderer.invoke('get-upa-cats'),
  scrapeUpaCat:  (id, name) => ipcRenderer.invoke('scrape-upa-cat', id, name),
  saveFile:      (opts)     => ipcRenderer.invoke('save-file', opts),
  copyImage:     (url)      => ipcRenderer.invoke('copy-image', url),
  downloadMultiple: (urls)   => ipcRenderer.invoke('download-multiple', urls),
  getAppPath:      ()        => ipcRenderer.invoke('get-app-path'),
  loadTags:        ()        => ipcRenderer.invoke('load-tags'),
  claudeApi:       (opts)    => ipcRenderer.invoke('claude-api', opts),
  getUpaUrls:      ()        => ipcRenderer.invoke('get-upa-urls'),
  fetchImageBase64:(url)     => ipcRenderer.invoke('fetch-image-base64', url),
  saveLocalImage:  (name, buf) => ipcRenderer.invoke('save-local-image', name, buf),
  openBrowser:   (url)      => ipcRenderer.invoke('open-browser', url),

  onCacheLoaded:    cb => ipcRenderer.on('cache-loaded',    (_, d) => cb(d)),
  onCacheProgress:  cb => ipcRenderer.on('cache-progress',  (_, d) => cb(d)),
  onCacheDone:      cb => ipcRenderer.on('cache-done',      (_, d) => cb(d)),
  onUcBuilding:     cb => ipcRenderer.on('uc-building',     (_, d) => cb(d)),
  onUcProgress:     cb => ipcRenderer.on('uc-progress',     (_, d) => cb(d)),
  onUcDone:         cb => ipcRenderer.on('uc-done',         (_, d) => cb(d)),
  onUcLoaded:       cb => ipcRenderer.on('uc-loaded',       (_, d) => cb(d)),
  onSplashProgress: cb => ipcRenderer.on('splash-progress', (_, d) => cb(d)),
  onSplashDone:      cb => ipcRenderer.on('splash-done',       (_, d) => cb(d)),
  onSplashPhase:     cb => ipcRenderer.on('splash-phase',      (_, d) => cb(d)),
  onSplashUcProgress:cb => ipcRenderer.on('splash-uc-progress',(_, d) => cb(d)),
  onSplashUcDone:    cb => ipcRenderer.on('splash-uc-done',    (_, d) => cb(d)),
  reloadSlug:        slug => ipcRenderer.invoke('reload-slug', slug),
  reloadAll:         ()   => ipcRenderer.invoke('reload-all'),
  onCtrlC:           cb  => ipcRenderer.on('ctrl-c-pressed', () => cb()),
  getUcVideo:        url  => ipcRenderer.invoke('get-uc-video', url),
  comboSearch:       tags => ipcRenderer.invoke('combo-search', tags),
  loadCollections:   ()   => ipcRenderer.invoke('load-collections'),
  saveCollections:   data => ipcRenderer.invoke('save-collections', data),
  loadTagProgress:  ()      => ipcRenderer.invoke('load-tag-progress'),
  saveTagProgress:  (data)  => ipcRenderer.invoke('save-tag-progress', data),
  getSlugNames:     ()      => ipcRenderer.invoke('get-slug-names'),
  loadEmbeddings:  ()           => ipcRenderer.invoke('load-embeddings'),
  voyageEmbed:     (opts)       => ipcRenderer.invoke('voyage-embed', opts),
  embedSearch:     (opts)       => ipcRenderer.invoke('embed-search', opts),

  r2SaveConfig:    (cfg)        => ipcRenderer.invoke('r2-save-config', cfg),
  r2LoadConfig:    ()           => ipcRenderer.invoke('r2-load-config'),
  r2UploadImage:   (opts)       => ipcRenderer.invoke('r2-upload-image', opts),
  r2ListImages:    (opts)       => ipcRenderer.invoke('r2-list-images', opts),
  r2UpdateTags:    (opts)       => ipcRenderer.invoke('r2-update-tags', opts),
  r2UpdateBrand:   (opts)       => ipcRenderer.invoke('r2-update-brand', opts),
  r2SaveEmbedding: (opts)       => ipcRenderer.invoke('r2-save-embedding', opts),
  r2EmbedSearch:   (opts)       => ipcRenderer.invoke('r2-embed-search', opts),
  r2ListBrands:    ()           => ipcRenderer.invoke('r2-list-brands'),
  r2AddBrand:      (opts)       => ipcRenderer.invoke('r2-add-brand', opts),
  r2UpdateBrandCategory: (opts) => ipcRenderer.invoke('r2-update-brand-category', opts),
  r2DeleteBrand:   (opts)       => ipcRenderer.invoke('r2-delete-brand', opts),
  r2DeleteImage:   (opts)       => ipcRenderer.invoke('r2-delete-image', opts),
})